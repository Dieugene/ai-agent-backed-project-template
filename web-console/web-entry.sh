#!/usr/bin/env bash
# Вход из браузера — то, что ttyd запускает на каждое подключение.
#
#   web-entry.sh role <пул> <роль>   → окно этой роли (через enter.sh: свой вид, заставы, уборка)
#   web-entry.sh pool <пул>          → пульт смены этого пула (enter.sh <пул>)
#   web-entry.sh desk                → пульт цеха (shop/shop-desk.sh)
#
# 🛑 АРГУМЕНТЫ ПРИХОДЯТ ИЗ АДРЕСНОЙ СТРОКИ БРАУЗЕРА (ttyd -a: ?arg=role&arg=team-live&arg=lead).
# За паролем прокси, но всё же от клиента: сюда попадает ЛЮБАЯ строка. Поэтому дальше уходит
# только то, что прошло форму (буквы-цифры-точка-дефис-подчёркивание, не длиннее 64) и счёт
# аргументов. Точность имён (пул есть, роль поднята) проверяет сам enter.sh целями «=имя».
#
# ⚠️ `exec` обязателен: ttyd при отключении клиента шлёт SIGHUP ПРОЦЕССУ, который запустил, —
# с exec это сам enter.sh, и его trap убирает вид. Без exec HUP получила бы эта обёртка, а
# enter.sh с видом остался бы сиротой до следующей уборки.
set -uo pipefail
CONSOLE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SHOP="${SHOP_DIR:-$HOME/workspace/.launcher/shop}"
# Пульты ждут fzf и pool из ~/.local/bin; у процесса из systemd-юнита PATH системный.
case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) export PATH="$HOME/.local/bin:$PATH" ;; esac
export TERM="${TERM:-xterm-256color}" LANG="${LANG:-en_US.UTF-8}"

ok_name() { case "${1:-}" in ''|*[!a-z0-9._-]*) return 1 ;; esac; [ "${#1}" -le 64 ]; }

# Сообщение остаётся на экране, пока панель не закроют (или минуту): без паузы панель мигнёт
# и опустеет, и человек не узнает, почему.
bye() {
  printf '\n  \033[38;5;179m%s\033[0m\n' "$1"
  printf '  \033[38;5;243mВходы: role <пул> <роль> · pool <пул> · desk\033[0m\n\n'
  read -rsn1 -t 60 -p '  любая клавиша — закрыть  ' || true
  exit 1
}

kind="${1:-}"
case "$kind" in
  role)
    [ $# -eq 3 ] || bye "Вход «role» ждёт два имени: пул и роль (получено $(($#-1)))."
    ok_name "$2" && ok_name "$3" || bye "Имя пула или роли не по форме: только a-z 0-9 . _ - до 64 знаков."
    exec bash "$CONSOLE/enter.sh" "$2" "$3"
    ;;
  pool)
    [ $# -eq 2 ] || bye "Вход «pool» ждёт одно имя: пул (получено $(($#-1)))."
    ok_name "$2" || bye "Имя пула не по форме: только a-z 0-9 . _ - до 64 знаков."
    exec bash "$CONSOLE/enter.sh" "$2"
    ;;
  desk)
    [ $# -eq 1 ] || bye "Вход «desk» аргументов не берёт."
    [ -f "$SHOP/shop-desk.sh" ] || bye "Пульта цеха нет на месте: $SHOP/shop-desk.sh"
    # 🛑 `--warp` значит «эта сторона умеет открывать окна». Без него пульт, войдя в роль, делает
    # attach ПРЯМО В СВОЕЙ панели: человек видит сессию под заголовком «пульт цеха», а заодно
    # уводит текущее окно рабочей сессии пула — он цепляется к ней самой, а не к своему виду.
    # С ключом пульт кладёт запрос в файл и выходит; запрос забирает страница и открывает панель.
    # ⚠️ Файл запроса — СВОЙ (`-web`): общий делят с ним локальный пульт и его обёртка, и первый
    # прочитавший забирает запрос себе.
    export SHOP_ACTION_FILE="${SHOP_ACTION_FILE:-$HOME/.shop/desk-action-web}"
    exec bash "$SHOP/shop-desk.sh" --warp
    ;;
  '')
    bye "Не сказано, куда входить."
    ;;
  *)
    # Печатаем НЕ сырой ввод: он мог прийти с управляющими последовательностями и нарисовать
    # в панели что угодно. Всё вне формы — знак вопроса.
    shown="${kind:0:40}"; shown="${shown//[^a-z0-9._-]/?}"
    bye "Неизвестный вход «$shown»."
    ;;
esac
