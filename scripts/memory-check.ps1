# memory-check.ps1 - структурная проверка каталога долговременной памяти роли.
#
# Ничего не чинит и ничего не удаляет: называет места, на которые стоит посмотреть.
# Все числа - маркеры, а не приговор: повод разобраться, что пошло не так, а не резать на автомате.
#
#   powershell -File memory-check.ps1 -Dir "<путь к .memory\<роль>>" [-Quiet]
#
# Проверки и их основания:
#   0. Якорь против впрыска   - после сжатия обвязка кладёт роли в контекст якорную запись, но не больше предела
#                               (`memory-inject.ps1`, 8000 знаков): лишнее вырезается СЕРЕДИНОЙ, и роль получает
#                               начало и старый хвост, а свежее состояние проваливается в дыру. Замер идёт тем же
#                               скриптом, что и впрыск, - чтобы проверка не разошлась с хуком. Первым по порядку:
#                               это единственные замечания, из-за которых роль восстанавливает контекст ЛОЖНО.
#                               Четыре исхода: ЯКОРЬ НЕ ДОЕЗЖАЕТ (длиннее предела), ЯКОРЬ НЕ ПО ИМЕНИ (впрыснется
#                               первая task_-ссылка оглавления, а не task_session_state.md), ЯКОРЬ ПУСТ (одна шапка),
#                               ЯКОРЯ НЕТ (впрыснется список задач). Нет измерителя или он не ответил - ЗАМЕР ЯКОРЯ
#                               НЕ ВЫПОЛНЕН, не тишина.
#   1. Потолок индекса        - движок обрезает MEMORY.md на 200 строках / 25000 знаках, с предупреждением.
#   2. Даты в теле записи     - лента дат значит, что записали хронику, а не знание; хроника живёт в задаче.
#   3. Хронологическое имя    - файл вида 2026-07-31.md не находится по предмету, а только по памяти о дне.
#   3a. Ссылка на саму себя   - след слияния: у поглощённой части осталась строка «Связано», вести ей некуда.
#                               Само по себе [[...]] никто не резолвит - ни движок, ни этот скрипт; висячая ссылка законна.
#   4. Сироты и битые ссылки  - тело без строки в индексе не будет прочитано никогда; строка без тела врёт.
#   5. Похожие строки индекса - две записи об одном предмете вместо одной обновлённой.
#   6. Нет признака условия   - СЛАБАЯ эвристика: у записи не видно момента срабатывания. Часто ложная,
#                               поэтому выводится последней и отдельно помечена.

param(
    [Parameter(Mandatory)][string]$Dir,
    [switch]$Quiet
)

$ErrorActionPreference = 'Stop'
# UTF-8 объявляем САМИ и первой строкой, а не наследуем от вызывающего: раньше проверка печатала UTF-8 как
# побочный эффект замера якоря (memory-inject.ps1 ставит кодировку внутрипроцессно) - и под родителем с
# OEM-консолью (CP866, Git Bash) самотест краснел на кириллице, а прежняя версия была зелёной (нашёл оппонент).
try { [Console]::OutputEncoding = New-Object System.Text.UTF8Encoding($false) } catch { }   # без преамбулы: BOM в stdout уезжал в контекст (замер компаньона)

if (-not (Test-Path -LiteralPath $Dir)) { Write-Host "НЕТ КАТАЛОГА: $Dir" -ForegroundColor Red; exit 2 }

$indexPath = Join-Path $Dir 'MEMORY.md'
$bodies = @(Get-ChildItem -LiteralPath $Dir -Filter '*.md' -File | Where-Object { $_.Name -ne 'MEMORY.md' })

$findings = New-Object System.Collections.Generic.List[string]
function Note([string]$s) { $findings.Add($s) | Out-Null }
$noinjectInfo = $false   # .noinject: не замечание (вечный красный приучает игнорировать), но и не тишина

# ---- 0. якорь против впрыска ---------------------------------------------
# Замер делает САМ скрипт впрыска (`-Measure`): тот же выбор файла, та же срезка шапки, тот же предел.
# Свой счёт здесь дал бы второй источник правды, и они бы разошлись молча - ровно так проверка и
# молчала про якорь до 17.08.2026 (у ведущего пула supervisors доезжало 10 % записи в 39 000 знаков,
# и после каждого сжатия он поднимался на состоянии пятидневной давности, не видя этого изнутри).
# Вызов оператором `&`, а не новым процессом: интерпретатор уже тот, что нужен на этой платформе.
# Отсутствие ответа - ЗАМЕЧАНИЕ, а не тишина: измеритель, которого нет, неотличим от «якорь в норме».
$injector = Join-Path $PSScriptRoot 'memory-inject.ps1'
if (Test-Path -LiteralPath $injector) {
    $mline = $null; $mwhy = ''
    try {
        foreach ($l in @(& $injector -Dir $Dir -Measure 2>&1)) { $t = "$l".TrimStart([char]0xFEFF); if ($t -match '^ANCHOR:') { $mline = $t; break } }
    } catch { $mline = $null; $mwhy = $_.Exception.Message }
    if (-not $mline) {
        Note ("ЗАМЕР ЯКОРЯ НЕ ВЫПОЛНЕН: memory-inject.ps1 -Measure не ответил{0}. Помещается ли якорь во впрыск - неизвестно." -f $(if ($mwhy) { " ($mwhy)" } else { '' }))
    } elseif ($mline -match '^ANCHOR: by=(name|index) chars=(\d+) limit=(\d+) delivered=(\d+) file=(.+)$') {
        $aBy = $Matches[1]; $aChars = [int]$Matches[2]; $aLimit = [int]$Matches[3]; $aPct = [int]$Matches[4]; $aFile = $Matches[5].Trim()
        if ($aBy -eq 'index') {
            # Впрыск ищет якорь ПО ИМЕНИ; иное имя ловится запасным проходом «первая task_-ссылка оглавления»,
            # и это держится ровно до тех пор, пока роль не допишет строку сверху (замер 09.08: 17 ролей из 44
            # получали не ту запись, заголовок был одинаковый). Размер этого файла - в ту же строку: отдельное
            # «НЕ ДОЕЗЖАЕТ» про рабочую задачу толкало бы резать не тот файл (нашёл оппонент).
            $size = if ($aChars -gt $aLimit) { " ($aChars знаков при пределе $aLimit - ещё и не помещается, доедет $aPct %)" } else { '' }
            Note "ЯКОРЬ НЕ ПО ИМЕНИ: файла task_session_state.md нет; после сжатия вклеится $aFile - просто первая task_-ссылка оглавления$size. Первая же новая строка сверху подменит её рабочей задачей. Завести якорь ровно под именем task_session_state.md (где остановился / следующий шаг / условия) и поставить строку на него первой."
        } elseif ($aChars -gt $aLimit) {
            Note "ЯКОРЬ НЕ ДОЕЗЖАЕТ: task_session_state.md - $aChars знаков, а после сжатия в контекст вклеивается не больше ${aLimit}: доедет $aPct % (начало и хвост, середина вырезана). Переписать сам якорь как СОСТОЯНИЕ короче $aLimit знаков (где остановился / следующий шаг / условия / открытые вопросы); сделанное - в предметные записи, историю помнит git. Оглавление тут ни при чём."
        }
    } elseif ($mline -match '^ANCHOR: empty') {
        # Якорь есть, тело пустое: впрыснется список задач, а «100 %» рапортовать нечего (стенд компаньона:
        # одна шапка, chars=51 считались содержанием).
        Note "ЯКОРЬ ПУСТ: у task_session_state.md есть только шапка - после сжатия впрыснется список задач, а не точка входа. Запиши состояние (где остановился / следующий шаг / условия)."
    } elseif ($mline -match '^ANCHOR: none') {
        # Без якоря впрыск после сжатия отдаёт список задач - роль восстанавливает контекст сама, то есть
        # не восстанавливает (пересказ выглядит полным). Молчать здесь значит прятать отказ там, где цена
        # потери максимальна.
        Note "ЯКОРЯ НЕТ: task_session_state.md не найден и в оглавлении нет ссылки на task_ - после сжатия впрыснется список задач, а не точка входа. Заведи якорь (где остановился / следующий шаг / условия) и поставь его строку ПЕРВОЙ в MEMORY.md."
    } elseif ($mline -match '^ANCHOR: off') {
        # Выключено нарочно (.noinject) - НЕ замечание (вечное красное к себе приучает: «ложная тревога
        # дороже пропуска»), но и не тишина: роль без точки входа при зелёной проверке - невидимый отказ
        # (приёмка 17.08). Отдельная строка ниже, в счёт замечаний не входит.
        $noinjectInfo = $true
    } elseif ($mline -match '^ANCHOR: error') {
        Note "ЗАМЕР ЯКОРЯ НЕ ВЫПОЛНЕН: $mline"
    } else {
        # Строка есть, но не разобралась - версии впрыска и проверки разошлись. Тишина здесь была бы «в норме».
        Note "ЗАМЕР ЯКОРЯ НЕ РАЗОБРАН: $mline"
    }
} else {
    Note "ЗАМЕР ЯКОРЯ НЕ ВЫПОЛНЕН: рядом с проверкой нет memory-inject.ps1. Помещается ли якорь во впрыск - неизвестно."
}

# ---- 1. индекс: потолок --------------------------------------------------
$idxLines = @(); $idxChars = 0
if (Test-Path -LiteralPath $indexPath) {
    $idxText = [System.IO.File]::ReadAllText($indexPath)
    $idxChars = $idxText.Length      # ENGINE COUNTS CHARS, NOT BYTES (measured: warning says 29.4KB == chars/1024)
    $idxLines = @($idxText.TrimEnd([char]13, [char]10) -split "`r?`n")
    $pctLines = [math]::Round(100 * $idxLines.Count / 200)
    $pctChars = [math]::Round(100 * $idxChars / 25000)
    if ($pctLines -ge 80 -or $pctChars -ge 80) {
        Note "ИНДЕКС близок к потолку: $($idxLines.Count)/200 строк ($pctLines%), $idxChars/25000 знаков ($pctChars%). Переполнение движок обрежет."
    }
    $long = @($idxLines | Where-Object { $_.Length -gt 200 })
    if ($long.Count) { Note "ИНДЕКС: строк длиннее 200 знаков - $($long.Count). Строка индекса несёт следствие, подробности - в теле." }
} else {
    Note "ИНДЕКСА НЕТ: $indexPath. Без него ни одна запись не попадёт в контекст автоматически."
}

# ---- 2-3. тела: даты внутри и хронологические имена -----------------------
$datePat = '(\d{4}-\d{2}-\d{2})|(\d{1,2}\.\d{1,2}\.\d{4})'
$selfRef = @()
foreach ($b in $bodies) {
    $t = [System.IO.File]::ReadAllText($b.FullName)
    # Шапка (frontmatter) из подсчёта ИСКЛЮЧЕНА: даты там служебные - modified, а с вводом
    # актуализации ещё и checked. Иначе метка проверки сама порождала бы замечание «ДАТЫ В ТЕЛЕ»
    # на каждом проходе, и шум рос бы монотонно от самой механики (замер: 33 записи в памяти
    # <supervisor-role> имеют ровно 2 даты и перешли бы порог от одной метки).
    $body = $t
    $fm = [regex]::Match($t, "(?s)^---\r?\n.*?\r?\n---\r?\n")
    if ($fm.Success) { $body = $t.Substring($fm.Length) }
    $hits = @([regex]::Matches($body, $datePat)).Count
    if ($hits -ge 3) { Note "ДАТЫ В ТЕЛЕ: $($b.Name) - $hits дат. Похоже на хронику; знание пишут без дат, «когда» помнит git." }
    if ($b.BaseName -match '^\d{4}[-.]\d{2}') { Note "ИМЯ ПО ДАТЕ: $($b.Name). Такой файл ищется только по памяти о дне, а не по предмету." }

    # Ссылка записи на саму себя. Висячая ссылка ошибкой НЕ считается (движок прямо разрешает ссылаться
    # на ещё не написанное), и машинного резолва у [[...]] нет ни у кого - ни в движке, ни здесь. Но
    # ссылка на себя не значит ничего ни при каком чтении, а вот следом слияния служит: у поглощённой
    # части осталась строка «Связано», вести ей больше некуда. Слияние - ровно та операция, на которой
    # теряется содержание, и другого её следа у нас нет. Сверяем с ОБЕИМИ формами адреса: движок велит
    # ссылаться по полю name, на диске ссылаются по имени файла, и законны обе.
    $nm = ''
    if ($t.StartsWith('---') -and $t -match '(?m)^name:[ \t]*(.+?)[ \t]*$') { $nm = $Matches[1].Trim().Trim('"') }
    $sc = 0
    foreach ($m in [regex]::Matches($t, '\[\[([^\]|]+)\]\]')) {
        $tgt = $m.Groups[1].Value.Trim()
        if ($tgt -eq $b.BaseName -or ($nm -and $tgt -eq $nm)) { $sc++ }
    }
    if ($sc) { $selfRef += "$($b.Name) x$sc" }
}
if ($selfRef.Count) {
    Note "ССЫЛКА НА СЕБЯ ($($selfRef.Count)): $($selfRef -join ', '). Запись отсылает к самой себе - обычно след слияния: у поглощённой части осталась строка «Связано», а вести ей больше некуда."
}

# ---- 4. сироты и битые ссылки --------------------------------------------
if ($idxLines.Count) {
    $linked = @()
    foreach ($l in $idxLines) {
        # Именно markdown-ссылка `](путь.md)`, а не любые скобки: на своей же памяти первая версия
        # приняла за ссылку перечисление в скобках «(pool-lifecycle, …→COORDINATION.md)» и выдала
        # две несуществующие «ссылки в никуда». Ложная тревога дороже пропуска: ей верят.
        foreach ($m in [regex]::Matches($l, '\]\(([^)\s]+\.md)\)')) { $linked += $m.Groups[1].Value }
    }
    # `-replace '\\','/'` до взятия имени - СТРАХОВКА, а не починка: заявленный приёмкой 17.08 дефект
    # («на Linux Split-Path вернёт ссылку с '\' целиком - две ложные тревоги») НЕ подтвердился замером
    # 18.08: Split-Path понимает оба слэша на обеих платформах (мутация со снятой заменой осталась
    # зелёной на Linux у компаньона). Замена оставлена от смены поведения Split-Path; её мутация
    # эквивалентна - тест не сторожит её по построению, и это норма.
    $linked = @($linked | ForEach-Object { Split-Path ($_ -replace '\\', '/') -Leaf } | Sort-Object -Unique)
    $names  = @($bodies | ForEach-Object { $_.Name })

    $orphans = @($names | Where-Object { $linked -notcontains $_ })

    # ⚠️ ЗАКРЫТАЯ задача законно живёт без строки в индексе: канон велит строку снять, а файл оставить
    # отчётом. Проверка этого не знала и ругалась на правильно сделанное — замер по рабочему
    # пространству: из 10 файлов вне индекса у 37 ролей закрытых оказалось 8, настоящих сирот 2.
    #
    # 🛑 Предикат намеренно УЗКИЙ, и расширять его нельзя. Опасность здесь несимметрична: ложная
    # тревога стоит минуты чужого времени, а ложное молчание прячет единственный случай, ради
    # которого проверка существует. Поэтому меткой считается только:
    #   - описание, НАЧИНАЮЩЕЕСЯ с «ЗАКРЫТО» (заглавными), либо
    #   - ПЕРВАЯ непустая строка тела с заглавным «ЗАКРЫТ…».
    # Не «где-то в первых N строках»: в живых записях заглавное «ЗАКРЫТ» сплошь встречается про
    # ПОДПУНКТЫ внутри открытой работы («Регламентный срок ЗАКРЫТ», «Шаги 1 и 2 ЗАКРЫТЫ»), и широкое
    # окно замолчало бы три живых записи, включая якорь «где я остановился» серверной роли.
    # Строчное «закрыта» не считаем вовсе — оно есть в обычном тексте; сравнение регистрозависимое
    # явно (-cmatch), обычный -match регистр игнорирует.
    #
    # ⛔ Контр-признак сильнее метки: описание, начинающееся с «ОТКРЫТО» или «НЕ », закрытой запись
    # не делает, что бы ни стояло в теле.
    # 📌 Проверено 07.08 и ОТВЕРГНУТО: распространить метку «ЗАКРЫТО» на записи прочих типов.
    # Повод был живой — методист pool-Y признал свою `reference_…` неверной, завёл взамен
    # новую, пометил старую «ЗАКРЫТО как неверная» и снял строку; проверка назвала её потерянной.
    # Правку остановил самотест (проверка 5 «послабление только для task_»), и он прав по существу:
    # канон оставляет без строки ЗАКРЫТУЮ ЗАДАЧУ — она отчёт о сделанном. Справка, оказавшаяся
    # неверной, каноном УДАЛЯЕТСЯ, а опровержение переносится в заменившую её запись; иначе в
    # хранилище копятся файлы, которые никто никогда не прочитает. ⇒ Замечание тут верное, менять
    # надо не проверку, а приём.
    $closedTasks = @()
    foreach ($o in $orphans) {
        if (-not $o.StartsWith('task_')) { continue }
        $bo = @($bodies | Where-Object { $_.Name -eq $o })
        if (-not $bo.Count) { continue }
        $tx    = [System.IO.File]::ReadAllText($bo[0].FullName)
        $desc  = ([regex]::Match($tx, '(?m)^description:[ \t]*"?(.*)$')).Groups[1].Value.Trim()
        # Тело = всё после шапки: окно считается от НАЧАЛА ТЕЛА, а не от начала файла (шапка занимает
        # девять непустых строк, и «первые 12 строк файла» оставляли телу всего три).
        $body  = $tx
        $fm    = [regex]::Match($tx, '(?s)^---.*?\r?\n---\r?\n')
        if ($fm.Success) { $body = $tx.Substring($fm.Length) }
        $first = @($body -split "`r?`n" | Where-Object { $_.Trim() } | Select-Object -First 1)
        $firstLine = if ($first.Count) { $first[0] } else { '' }
        $openly = ($desc -cmatch '^(ОТКРЫТО|НЕ )')
        if (-not $openly -and (($desc -cmatch '^ЗАКРЫТ') -or ($firstLine -cmatch 'ЗАКРЫТ'))) { $closedTasks += $o }
    }
    $orphans = @($orphans | Where-Object { $closedTasks -notcontains $_ })
    if ($orphans.Count) {
        # ⚠️ Подсказка даётся ОБЕИМИ ветками. Прежняя редакция советовала только пометить закрытие —
        # то есть настоящей пропаже предлагала способ замолчать вместо способа починиться.
        Note "НЕ В ИНДЕКСЕ ($($orphans.Count)): $($orphans -join ', '). Тело без строки в индексе не прочитают. Задача открыта — верни строку в оглавление; закрыта — начни её описание словом ЗАКРЫТО."
    }

    $broken = @($linked | Where-Object { $names -notcontains $_ })
    if ($broken.Count) { Note "ССЫЛКА В НИКУДА ($($broken.Count)): $($broken -join ', '). Строка индекса обещает файл, которого нет." }
}

# ---- 5. похожие строки индекса -------------------------------------------
if ($idxLines.Count) {
    $norm = @{}
    foreach ($l in $idxLines) {
        if ($l -notmatch '\S') { continue }
        $k = ($l -replace '\[[^\]]*\]\([^)]*\)','' -replace '[^\p{L}\p{Nd}]+',' ').Trim().ToLower()
        if ($k.Length -lt 12) { continue }
        $words = @($k -split '\s+' | Where-Object { $_.Length -gt 3 })
        if ($words.Count -lt 3) { continue }
        $sig = ($words | Sort-Object | Select-Object -First 6) -join ' '
        if ($norm.ContainsKey($sig)) { Note "ПОХОЖИЕ СТРОКИ ИНДЕКСА: «$($norm[$sig])» и «$($l.Trim())». Один предмет - одна запись, обновляемая." }
        else { $norm[$sig] = $l.Trim() }
    }
}

# ---- 6. слабая эвристика: не видно условия --------------------------------
$weak = @()
foreach ($b in $bodies) {
    $t = [System.IO.File]::ReadAllText($b.FullName)
    if ($t.Length -lt 80) { continue }
    if ($t -notmatch '(?i)если|когда|при |пока |иначе|потому|поэтому|причина|основание|как применять|срабатыва') { $weak += $b.Name }
}

# ---- отчёт ---------------------------------------------------------------
if (-not $Quiet) {
    Write-Host "память: $Dir" -ForegroundColor Cyan
    Write-Host ("записей: {0}   индекс: {1} строк / {2} знаков" -f $bodies.Count, $idxLines.Count, $idxChars)
}
if ($findings.Count -eq 0) { Write-Host "структурных замечаний нет" -ForegroundColor Green }
else { foreach ($f in $findings) { Write-Host "  - $f" -ForegroundColor Yellow } }

if ($weak.Count) {
    Write-Host "  ~ слабая эвристика (часто ложная): не видно момента срабатывания у $($weak.Count) записей: $($weak -join ', ')" -ForegroundColor DarkGray
}

# Не через Note намеренно: выключатель - осознанное состояние, а не дефект, и вечное замечание на борде
# приучало бы к красному. Но тишина прятала бы роль без точки входа за зелёной проверкой.
# Префикс `*`, а не `- `: memory-audit собирает замечания по образцу '^\s+- ', эта строка - не оно.
if ($noinjectInfo) {
    Write-Host "  * впрыск выключен нарочно (.noinject): после сжатия роль НЕ получит точку входа. Якорь починен - удали файл .noinject." -ForegroundColor DarkYellow
}

# 🛑 Машинный хвост для вызывающих. Раньше счёт замечаний выводился ИЗ ОФОРМЛЕНИЯ: memory-audit и
# memory-board считали строки по образцу `^\s+- `, то есть по отступу и цвету Write-Host. Любая смена
# оформления, локали или платформы обнуляла счёт МОЛЧА, и упавшая проверка была неотличима от чистой
# памяти (так и вышло на сервере: интерпретатор не нашёлся, строк не пришло вовсе, напечаталось
# «замечаний нет»). Теперь у вызывающего есть ПОЛОЖИТЕЛЬНЫЙ признак: нет этой строки - проверка не
# состоялась, что бы ни лежало в выводе.
# Write-Output, а не Write-Host: цветной вывод под pwsh на Linux несёт ANSI-escape в stdout, и образец
# по началу строки об него спотыкается. Только под -Quiet: этот режим значит «зовёт программа».
# ---- актуализация памяти: указатель на список мест -----------------------
# Список собирается ОТДЕЛЬНОЙ командой и лежит ВНЕ каталога памяти (иначе аудит памяти увидит
# правку каждый ход и его коммиты потеряют смысл). Здесь только указатель: роль и так обязана
# прийти за выводом этой проверки, а второй канал находок она проверяла бы через раз.
$revRoot  = Split-Path -Parent (Split-Path -Parent $Dir)
$revFile  = Join-Path (Join-Path $revRoot '.revision') ((Split-Path -Leaf $Dir) + '.md')
if (Test-Path -LiteralPath $revFile) {
    $revPlaces = @(Select-String -LiteralPath $revFile -Pattern '^### ').Count
    $revAge    = [math]::Round(((Get-Date) - (Get-Item -LiteralPath $revFile).LastWriteTime).TotalHours, 1)
    Write-Host ("  АКТУАЛИЗАЦИЯ: {0} пунктов, собран {1} ч назад -> {2}" -f $revPlaces, $revAge, $revFile) -ForegroundColor Cyan
    # 🛑 Путь закрывателя называем ЗДЕСЬ, а не в каноне: канон — один текст на обе машины, а пути
    # к модулю на них разные (на сервере он в shop/). Роль берёт и список, и инструмент из одной
    # строки; нет строки — значит инструмента нет, и канон велит вписывать исходы руками.
    $closer = @(
        (Join-Path $PSScriptRoot 'memory-revision\memory-close.py'),
        (Join-Path $PSScriptRoot '..\server\memory-revision\memory-close.py'),
        (Join-Path $PSScriptRoot '..\shop\memory-close.py')
    ) | Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1
    if ($closer) {
        Write-Host ("  АКТУАЛИЗАЦИЯ: исходы закрывать ПАЧКОЙ -> {0}" -f (Resolve-Path -LiteralPath $closer).Path) -ForegroundColor Cyan
    }
    # Вердикты помощника считаются фоном; роль, открывшая каталог до конца расчёта, видела «файла
    # нет» и не знала, что он в пути (координатор pool-B 05.09). Замок расчёта — и есть признак.
    $roleName = Split-Path -Leaf $Dir
    $vLock = Join-Path (Join-Path $revRoot '.revision') ('.verdicts-lock-' + $roleName)
    $vFile = Join-Path (Join-Path $revRoot '.revision') ('verdicts-' + $roleName + '.md')
    if (Test-Path -LiteralPath $vLock) {
        Write-Host ("  ВЕРДИКТЫ: считаются с {0} (замок стоит) — файл появится: {1}; чего нет — разбирай сам" -f (Get-Item -LiteralPath $vLock).CreationTime.ToString('HH:mm'), $vFile) -ForegroundColor Yellow
    } elseif (-not (Test-Path -LiteralPath $vFile)) {
        Write-Host "  ВЕРДИКТЫ: файла нет и расчёт не идёт — разбирай пункты сам" -ForegroundColor Yellow
    }
    # Устаревший список неотличим от свежего, если не сказать возраст словом: посчитанный по
    # памяти многодневной давности, он закрывался бы как актуальный.
    if ($revAge -gt 24) { Write-Host "  АКТУАЛИЗАЦИЯ: список СТАРШЕ СУТОК - пересобери, память с тех пор менялась." -ForegroundColor Yellow }
    if ($Quiet) { Write-Output ("REVISION: places={0}" -f $revPlaces) }
} else {
    Write-Host ("  АКТУАЛИЗАЦИЯ: список не собран (нет {0}). Собрать модулем memory-revision.py" -f $revFile) -ForegroundColor Cyan
    if ($Quiet) { Write-Output "REVISION: places=none" }
}

if ($Quiet) { Write-Output ("RESULT: findings={0}" -f $findings.Count) }

exit 0
